/**
 * Адрес входящего вебхука Битрикс24: https://портал/rest/<номер пользователя>/<код>/
 * (облако или коробка; коробка в локальной сети бывает и по http). Опечатка
 * или ссылка на другую страницу ловится при сохранении, а не потом — молча
 * копящимися ошибками отправки. Чистая функция — проверяется тестами.
 */
export function bitrixWebhookProblem(raw: string): string | null {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return "Адрес вебхука не похож на ссылку — скопируйте его целиком из Битрикс24 (Разработчикам → Входящий вебхук)";
  }
  if (url.protocol !== "https:" && url.protocol !== "http:") return "Адрес вебхука должен начинаться с https://";
  if (url.username || url.password) return "В адресе вебхука не должно быть логина и пароля — только ссылка из Битрикс24";
  if (!/^\/rest\/\d+\/[A-Za-z0-9_]+\/?$/.test(url.pathname)) {
    return "Это не адрес входящего вебхука: он выглядит как https://ваш-портал.bitrix24.ru/rest/1/код/ — скопируйте его в Битрикс24 (Разработчикам → Входящий вебхук)";
  }
  return null;
}

/** Сколько ждать ответа Битрикс24: зависший адрес не должен держать очередь. */
export const BITRIX_TIMEOUT_MS = 15_000;
